"""Voice Capability Registry for Agent 06.

Registers, inspects, and queries available voice capabilities across
DevTone, Windows System SAPI, Kokoro ONNX, Piper ONNX, and Azure Speech.
"""
from __future__ import annotations

from typing import Dict, List, Optional
from app.core.logging import get_logger
from app.models.voice_profile import VoiceCapability

logger = get_logger(__name__)


class VoiceRegistry:
    """In-memory registry of all known voice capabilities."""

    def __init__(self) -> None:
        self._voices: Dict[str, VoiceCapability] = {}
        self._seed_default_capabilities()

    def register(self, voice: VoiceCapability) -> None:
        """Register or update a voice capability."""
        self._voices[voice.voice_id] = voice
        logger.debug(
            "Registered voice capability",
            extra={"voice_id": voice.voice_id, "provider": voice.provider, "language": voice.language},
        )

    def get(self, voice_id: str) -> Optional[VoiceCapability]:
        """Lookup a voice by ID."""
        return self._voices.get(voice_id)

    def list_all(
        self,
        language: Optional[str] = None,
        provider: Optional[str] = None,
        only_local: bool = False,
        only_available: bool = True,
    ) -> List[VoiceCapability]:
        """Filter and list registered voice capabilities."""
        results: List[VoiceCapability] = []
        for voice in self._voices.values():
            if only_available and not voice.is_available:
                continue
            if only_local and not voice.is_local:
                continue
            if provider and voice.provider.lower() != provider.lower():
                continue
            if language:
                lang_clean = language.lower().split("-")[0].split("_")[0]
                v_lang_clean = voice.language.lower().split("-")[0].split("_")[0]
                if lang_clean != v_lang_clean and voice.language != "*":
                    continue
            results.append(voice)
        return results

    def find_best_for_language(
        self,
        language: str,
        preferred_provider: Optional[str] = None,
        gender: Optional[str] = None,
        offline_only: bool = False,
    ) -> Optional[VoiceCapability]:
        """Find the most suitable voice for a target language."""
        candidates = self.list_all(language=language, only_local=offline_only, only_available=True)
        if not candidates:
            return None

        # Filter by preferred provider if specified
        if preferred_provider:
            prov_matches = [v for v in candidates if v.provider.lower() == preferred_provider.lower()]
            if prov_matches:
                candidates = prov_matches

        # Filter by gender if specified
        if gender:
            gender_matches = [v for v in candidates if v.gender and v.gender.lower() == gender.lower()]
            if gender_matches:
                candidates = gender_matches

        # Sort priority: neural (edge_tts/edge > azure > kokoro > piper > system > dev_tone)
        priority = {"edge": 1, "edge_tts": 1, "azure": 2, "kokoro": 3, "piper": 4, "system": 5, "dev_tone": 9}
        candidates.sort(key=lambda v: priority.get(v.provider.lower(), 99))
        return candidates[0]

